SELECT CONCAT(E.LAST_NAME, ', ', E.FIRST_NAME) AS NOM, E.JOB_ID, J.JOB_TITLE
FROM employees E
JOIN jobs J
USING (JOB_ID)
ORDER BY NOM;
-- 2.0 --
SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, L.CITY, L.STATE_PROVINCE
FROM departments D
JOIN locations L
USING (LOCATION_ID)
ORDER BY D.DEPARTMENT_NAME;
-- 2.1 --
SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, L.CITY, L.STATE_PROVINCE
FROM departments D
JOIN locations L
USING (LOCATION_ID)
WHERE D.DEPARTMENT_ID IN (20, 60, 80)
ORDER BY D.DEPARTMENT_ID;
-- 3 --
SELECT R.REGION_ID, R.REGION_NAME, C.COUNTRY_NAME
FROM REGIONS R
JOIN COUNTRIES C
USING (REGION_ID)
WHERE R.REGION_NAME = 'EUROPE'
ORDER BY C.COUNTRY_NAME;
-- 4.0 --
SELECT J.JOB_ID, J.JOB_TITLE, CONCAT(E.FIRST_NAME, '-', E.LAST_NAME) AS NOM
FROM JOBS J
JOIN EMPLOYEES E
USING(JOB_ID)
WHERE J.JOB_TITLE LIKE 'SALES%';
-- 4.1 --
SELECT J.JOB_ID, J.JOB_TITLE, COUNT(*) AS Numero_Empleats
FROM JOBS J
JOIN EMPLOYEES E
USING (JOB_ID)
WHERE J.JOB_TITLE LIKE 'SALES%'
GROUP BY J.JOB_ID, J.JOB_TITLE;
-- 5 --
SELECT D.DEPARTMENT_NAME, L.LOCATION_ID, L.STATE_PROVINCE
FROM DEPARTMENTS D
JOIN LOCATIONS L
USING (LOCATION_ID)
WHERE L.STATE_PROVINCE='Washington';
-- 6 --
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, COUNT(*) AS 'Numero de feines'
FROM EMPLOYEES E
JOIN JOB_HISTORY H
USING(EMPLOYEE_ID)
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME
ORDER BY E.FIRST_NAME;
-- 7 --
SELECT D.DEPARTMENT_NAME
FROM DEPARTMENTS D
JOIN LOCATIONS L USING(LOCATION_ID)
JOIN COUNTRIES C USING(COUNTRY_ID)
WHERE C.COUNTRY_ID= 'US'
ORDER BY 1;
